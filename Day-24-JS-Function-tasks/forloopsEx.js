//1lakh to 2lakh
for (let i = 100000; i <= 200000; i++) {
    console.log(i);
}

//print square number sequence
for(let i=1; i<=10; i++) {
    console.log(i * i);
}

//print cube number sequence
for(let i=1; i<=10; i++) {
    console.log(i * i * i);
}

//5lakh to 4lakh reverse order
for (let i = 500000; i >= 400000; i--) {
    console.log(i);
}

//print 2.5 2 1.5 1 0.5 0
for (let i = 2.5; i >= 0; i -= 0.5) {
    console.log(i);
}